import { describe, expect, it } from "vitest";
import { checkCommitIdentity, checkCommitMessage, MAX_HEADER_LENGTH } from "../scripts/commit-message.mts";

describe("commit messages", () => {
  it.each([
    "feat: add the portfolio",
    "fix(cv): keep the download name",
    "refactor(docs)!: move guides into folders",
    "chore: bump next",
    "docs: explain the design tokens\n\nA longer body is fine.",
    "# a comment git strips\nci: check commit messages",
  ])("accepts %j", (message) => {
    expect(checkCommitMessage(message)).toBeNull();
  });

  it.each(["Merge pull request #7 from x/y", 'Revert "feat: x"', "fixup! feat: x"])(
    "leaves git's own %j alone",
    (message) => {
      expect(checkCommitMessage(message)).toBeNull();
    },
  );

  it.each([
    "Add the portfolio",
    "feature: add the portfolio",
    "feat:add the portfolio",
    "feat(CV): shout",
    "Feat: capitalised type",
    "",
  ])("rejects %j", (message) => {
    expect(checkCommitMessage(message)).not.toBeNull();
  });

  it.each([
    "feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>",
    "feat: x\n\nco-authored-by: Someone <someone@example.com>",
    "fix: x\n\nClaude-Session: https://example.com/session_1",
    "docs: x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)",
    "docs: x\n\n_Generated by Claude Code_",
    "chore: x\n\nSee https://claude.ai/code/session_1",
    "fixup! feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>",
  ])("rejects the AI trace in %j", (message) => {
    expect(checkCommitMessage(message)).toMatch(/carries/);
  });

  it("still allows the docs/claude scope and the word in a body", () => {
    expect(checkCommitMessage("docs(claude): document the content column")).toBeNull();
    expect(checkCommitMessage("docs: point CLAUDE.md at the rules\n\nClaude reads CLAUDE.md first.")).toBeNull();
  });

  it.each(["Claude <noreply@anthropic.com>", "claude <someone@example.com>", "Bot <noreply@anthropic.com>"])(
    "rejects the AI identity %j",
    (ident) => {
      expect(checkCommitIdentity("author", ident)).toMatch(/commit as yourself/);
    },
  );

  it.each(["ducdam-dev <ducdam.dev@gmail.com>", "Dam Hong Duc <hongduc001h@gmail.com>", "GitHub <noreply@github.com>"])(
    "accepts the identity %j",
    (ident) => {
      expect(checkCommitIdentity("committer", ident)).toBeNull();
    },
  );

  it("rejects a first line that runs long", () => {
    expect(checkCommitMessage(`feat: ${"x".repeat(MAX_HEADER_LENGTH)}`)).toMatch(/characters/);
  });
});
